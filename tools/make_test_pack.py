"""
make_test_pack.py — build a folder of generated disk images, reference photos and ground-truth clips you can load into
the tool and check against KNOWN answers.

    python tools/make_test_pack.py "C:/path/to/sih-test-pack"            build + self-check
    python tools/make_test_pack.py OUT --photo-a me.jpg --photo-b friend.jpg   use your own (consented) photos
    python tools/make_test_pack.py OUT --quick                             tiny 4-second version (used by the tests)

HONEST LIMITS: everything here is generated by us. The people are cartoon avatars (or your own photos), the video is
rendered, and the recorder layouts are built from the public specifications the tool implements. Nothing here has been
written by a physical DVR/NVR, so it can show that the tool's plumbing works and that its results match what we put in;
it cannot show that a real recorder's disk will decode.
"""

